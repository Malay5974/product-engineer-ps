import { spawn, type ChildProcess } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { setTimeout as wait } from "node:timers/promises";

const port = 39127;
const baseUrl = `http://127.0.0.1:${port}`;
const directory = mkdtempSync(join(tmpdir(), "caygnus-benchmark-"));
const database = join(directory, "conversation.db");
const startedAt = Date.now();
const report: string[] = [
  "# Benchmark report",
  "",
  `Generated: ${new Date().toISOString()}`,
  "",
  "This report was generated by the real HTTP/SSE integration benchmark.",
  "",
  "| Scenario | Result | What was verified |",
  "| --- | --- | --- |",
];

function addReport(scenario: string, details: string): void {
  report.push(`| ${scenario} | PASS | ${details} |`);
}

function log(phase: string, details: Record<string, unknown> = {}): void {
  console.log(
    JSON.stringify({ phase, elapsedMs: Date.now() - startedAt, ...details }),
  );
}

async function waitForServer(): Promise<void> {
  for (let attempt = 0; attempt < 100; attempt++) {
    try {
      const response = await fetch(`${baseUrl}/api/runs/missing`);
      if (response.status === 404) return;
    } catch {
      // The server is still starting.
    }
    await wait(25);
  }
  throw new Error("backend did not start");
}

function startServer(): ChildProcess {
  const child = spawn(
    process.execPath,
    ["node_modules/tsx/dist/cli.mjs", "server/index.ts"],
    {
      env: { ...process.env, PORT: String(port), DB_FILE: database },
      stdio: ["ignore", "pipe", "pipe"],
    },
  );
  child.stderr.on("data", (data) => process.stderr.write(`[server] ${data}`));
  return child;
}

async function stopServer(child: ChildProcess): Promise<void> {
  if (child.exitCode !== null) return;
  child.kill("SIGTERM");
  await new Promise<void>((resolve) => child.once("exit", () => resolve()));
}

async function createRun(
  options: Record<string, unknown>,
): Promise<{ id: string }> {
  const response = await fetch(`${baseUrl}/api/runs`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      conversationId: "integration-benchmark",
      input: "benchmark",
      ...options,
    }),
  });
  if (!response.ok) throw new Error(`create run failed: ${response.status}`);
  return (await response.json()) as { id: string };
}

type Event = { sequence: number; kind: string; payload: string };

async function readSse(
  runId: string,
  cursor: number,
  limit = Number.POSITIVE_INFINITY,
): Promise<Event[]> {
  const response = await fetch(
    `${baseUrl}/api/runs/${runId}/events?cursor=${cursor}`,
  );
  if (!response.ok || !response.body)
    throw new Error(`SSE request failed: ${response.status}`);
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  const events: Event[] = [];
  while (events.length < limit) {
    const chunk = await reader.read();
    if (chunk.done) break;
    buffer += decoder.decode(chunk.value, { stream: true });
    const messages = buffer.split("\n\n");
    buffer = messages.pop() ?? "";
    for (const message of messages) {
      const data = message
        .split("\n")
        .find((line) => line.startsWith("data: "));
      if (!data) continue;
      events.push(JSON.parse(data.slice(6)) as Event);
      if (events.length >= limit) break;
    }
  }
  await reader.cancel();
  return events;
}

async function waitForRun(runId: string, state: string): Promise<void> {
  for (let attempt = 0; attempt < 200; attempt++) {
    const response = await fetch(`${baseUrl}/api/runs/${runId}`);
    const body = (await response.json()) as { run: { state: string } };
    if (body.run.state === state) return;
    await wait(10);
  }
  throw new Error(`run ${runId} did not reach ${state}`);
}

async function main(): Promise<void> {
  let server = startServer();
  await waitForServer();
  log("backend_started", { port, database });

  const run = await createRun({ count: 30, delayMs: 5 });
  const received = await readSse(run.id, 0, 4);
  const cursor = received.at(-1)?.sequence ?? 0;
  log("disconnect_reconnect_started", {
    runId: run.id,
    cursor,
    receivedBeforeDisconnect: received.length,
  });
  await waitForRun(run.id, "completed");
  const replayed = await readSse(run.id, cursor);
  const combined = [...received, ...replayed];
  const sequences = combined.map((event) => event.sequence);
  const unique = new Set(sequences);
  const expected = Array.from({ length: 32 }, (_, index) => index + 1);
  const missing = expected.filter((sequence) => !unique.has(sequence));
  const duplicates = sequences.length - unique.size;
  if (missing.length || duplicates || sequences.length !== expected.length)
    throw new Error(
      `disconnect/reconnect failed: missing=${missing.length} duplicates=${duplicates}`,
    );
  log("disconnect_reconnect_passed", {
    expectedEvents: expected.length,
    observedEvents: sequences.length,
    replayedEvents: replayed.length,
    missingEvents: missing.length,
    duplicateEvents: duplicates,
    finalState: "completed",
  });
  addReport(
    "Disconnect and reconnect",
    `${sequences.length}/${expected.length} events reconstructed; missing ${missing.length}; duplicates ${duplicates}; final state completed`,
  );

  const failedRun = await createRun({ count: 5, delayMs: 1, failAt: 2 });
  await waitForRun(failedRun.id, "failed");
  const failedResponse = await fetch(`${baseUrl}/api/runs/${failedRun.id}`);
  const failedBody = (await failedResponse.json()) as {
    events: Event[];
    run: { state: string };
  };
  log("provider_failure_passed", {
    runId: failedRun.id,
    partialChunks: failedBody.events.filter((event) => event.kind === "chunk")
      .length,
    finalState: failedBody.run.state,
    terminalEvent: failedBody.events.at(-1)?.kind,
  });
  addReport(
    "Provider failure",
    `${failedBody.events.filter((event) => event.kind === "chunk").length} partial chunks retained; terminal event run_failed; final state failed`,
  );

  const restartRun = await createRun({ count: 8, delayMs: 20 });
  const beforeRestart = await readSse(restartRun.id, 0, 3);
  const restartCursor = beforeRestart.at(-1)?.sequence ?? 0;
  await stopServer(server);
  log("backend_stopped", { runId: restartRun.id, cursor: restartCursor });
  server = startServer();
  await waitForServer();
  const afterRestart = await readSse(restartRun.id, restartCursor);
  await waitForRun(restartRun.id, "completed");
  const restartSequences = [...beforeRestart, ...afterRestart].map(
    (event) => event.sequence,
  );
  const restartUnique = new Set(restartSequences);
  if (restartSequences.length !== 10 || restartUnique.size !== 10)
    throw new Error(
      "service restart recovery produced missing or duplicate events",
    );
  log("service_restart_passed", {
    eventsBeforeRestart: beforeRestart.length,
    eventsAfterRestart: afterRestart.length,
    reconstructedEvents: restartSequences.length,
    duplicateEvents: restartSequences.length - restartUnique.size,
    finalState: "completed",
  });
  addReport(
    "Backend stop and restart",
    `${restartSequences.length} durable events reconstructed; duplicates ${restartSequences.length - restartUnique.size}; final state completed`,
  );

  const invalidCursor = await fetch(
    `${baseUrl}/api/runs/${run.id}/events?cursor=9999`,
  );
  if (invalidCursor.status !== 400)
    throw new Error(`invalid cursor returned ${invalidCursor.status}`);
  log("invalid_cursor_passed", {
    expectedStatus: 400,
    observedStatus: invalidCursor.status,
  });
  addReport("Invalid cursor", "invalid cursor rejected with HTTP 400");
  report.push(
    "",
    "## Summary",
    "",
    "All four integration scenarios passed.",
    "",
  );
  writeFileSync("benchmark-report.md", `${report.join("\n")}\n`);
  log("benchmark_passed", {
    scenarios: 4,
    backend: "real HTTP and SSE",
    finalState: "completed",
  });
  await stopServer(server);
  rmSync(directory, { recursive: true, force: true });
}

main().catch((error) => {
  console.error(error);
  rmSync(directory, { recursive: true, force: true });
  process.exitCode = 1;
});
